'use strict';
/**
 * The changelog is the single source of release copy, and release copy is read by
 * users -- on GitHub and in the store listings. These tests put both claims in the
 * gate: the current version must have a section, its highlights must be store-safe
 * plain text, the store listing must still match them, and none of that copy may
 * talk about how the extension is built.
 */
const fs = require('fs');
const path = require('path');
const { test, assert } = require('./harness');
const notes = require('../scripts/release-notes');

const version = notes.pkgVersion();

// STORE-LISTING.md is internal and gitignored (see test/publishable.test.js), so
// it is absent from every fresh clone and from CI. Tests that read it must say so
// out loud instead of assuming the author's working tree.
const LISTING = path.join(__dirname, '..', '..', 'STORE-LISTING.md');
function listingMissing(label) {
  if (fs.existsSync(LISTING)) return false;
  console.log('    ! ' + label + ': STORE-LISTING.md not present (internal file), skipped');
  return true;
}

test('release notes: the changelog has a section for the current version', () => {
  const s = notes.section(version);
  assert.includes(s.heading, version, 'heading does not carry the version');
  assert.ok(s.body.length > 200, 'section body is suspiciously short');
  assert.ok(/^## \[/.test(s.body), 'section does not start at its own heading');
  assert.ok(!/\n## \[/.test(s.body), 'section ran into the next release');
});

test('release notes: highlights survive being stripped to plain text', () => {
  const items = notes.highlights(version);
  assert.ok(items.length > 0, 'no highlights');
  assert.ok(items.length <= notes.MAX_HIGHLIGHTS,
    items.length + ' highlights is more than a store field should carry');
  for (const item of items) {
    // Store fields render markup literally, so a stray ** or backtick is visible
    // to every reader of the listing.
    assert.ok(!/[*`]/.test(item), 'markup left in a highlight: ' + JSON.stringify(item));
    assert.ok(!/\]\(/.test(item), 'link syntax left in a highlight: ' + JSON.stringify(item));
    assert.ok(!/ -- /.test(item), 'ASCII dash pair left in a highlight: ' + JSON.stringify(item));
    assert.ok(item.length > 10, 'highlight too short to be useful: ' + JSON.stringify(item));
    assert.ok(item.length <= 180, 'highlight too long for a store field: ' + JSON.stringify(item));
  }
});

test('release notes: markdown is stripped, not mangled', () => {
  assert.equal(notes.plain('**Bold** and `code` and [text](https://x.y)'),
    'Bold and code and text');
  assert.equal(notes.plain('one -- two'), 'one \u2014 two');
});

test('release notes: the store listing matches the changelog highlights', () => {
  if (listingMissing('store listing matches changelog')) return;
  const problems = notes.checkListing(version);
  assert.ok(problems.length === 0, problems.join(' | '));
});

test('release notes: the listing carries one current block per language', () => {
  if (listingMissing('one listing block per language')) return;
  const blocks = notes.listingBlocks();
  const langs = blocks.map(b => b.lang).sort().join(',');
  assert.equal(langs, 'en,fa',
    'expected one English and one Persian block, got: '
      + JSON.stringify(blocks.map(b => b.heading)));
  for (const b of blocks) {
    assert.ok(notes.bulletCount(b.text) > 0, 'no bullets in the ' + b.lang + ' block');
  }
});

// Development detail kept leaking into copy that users read: test counts, script
// names, build machinery. It reads as noise to everyone outside the repository, so
// the vocabulary is now a gate rather than a habit. Contributor docs are exempt --
// this list is checked only against the two user-facing release documents.
const DEV_VOCABULARY = [
  /\btests?\b/i, /\btesting\b/i, /\bharness(es)?\b/i, /\bsuites?\b/i, /\bheadless\b/i,
  /\bregressions?\b/i, /\bassert(s|ed|ion|ions)?\b/i, /\bnpm\b/i, /\bCI\b/, /\blint(er|ing)?\b/i,
  /\brefactor(ed|ing)?\b/i, /\bschemas?\b/i, /\bmigrations?\b/i, /\bgitattributes\b/i,
  /\bcodebase\b/i, /\brepository's own\b/i, /\bstub(s|bed)?\b/i, /\bfixtures?\b/i,
  /\bthe gate\b/i, /\bpull request\b/i, /\bunit\b/i
];

const USER_FACING_DOCS = [
  path.join(__dirname, '..', 'CHANGELOG.md'),
  path.join(__dirname, '..', '..', 'STORE-LISTING.md')
];

test('release notes: the generated release body is not stale', () => {
  // Generated by `npm run release:notes -- --write` and gitignored, so it is
  // absent in CI and present locally -- where it can sit a release behind the
  // changelog it was derived from. Whenever it exists, it must still match.
  const out = path.join(__dirname, '..', 'RELEASE-NOTES.md');
  if (!fs.existsSync(out)) return;
  const expected = notes.section(version).body + '\n';
  assert.equal(fs.readFileSync(out, 'utf8'), expected,
    'RELEASE-NOTES.md no longer matches the ' + version
      + ' changelog section; regenerate with: npm run release:notes -- --write');
});

test('release notes: user-facing release copy contains no development detail', () => {
  const offences = [];
  for (const file of USER_FACING_DOCS) {
    if (!fs.existsSync(file)) continue; // STORE-LISTING.md is not published
    const lines = fs.readFileSync(file, 'utf8').split('\n');
    lines.forEach((line, i) => {
      for (const re of DEV_VOCABULARY) {
        if (re.test(line)) {
          offences.push(path.basename(file) + ':' + (i + 1) + ' ' + re + ' -> ' + line.trim());
        }
      }
    });
  }
  assert.ok(offences.length === 0, offences.join('\n      '));
});
