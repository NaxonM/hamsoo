  // Iran's only IANA zone, plus the legacy alias some systems still report.
  const IRAN_ZONES = /^(Asia\/Tehran|Iran)$/i;

  // Pure, so it is unit-testable: both impure inputs are passed in.
  //
  // Why the timezone is consulted at all: Firefox and Chrome both ship to Iran
  // with an English interface, so a large share of Persian-speaking users have
  // ui = 'en-US'. Reading that as "wants an English interface" is exactly why
  // the welcome tour opened in English for the audience this extension exists
  // for. The timezone is an independent second signal and Asia/Tehran is
  // unambiguous. It only ever supplies a *default*: resolveLang returns early on
  // a stored preference, so an explicit choice always wins.
  //
  // Deliberately not extended to Arabic: its zones are shared with several other
  // languages, so that guess would be wrong often enough to be worse than 'en'.
  function langFromLocaleAndZone(uiLang, zone) {
    const ui = String(uiLang || '');
    if (/^ar/i.test(ui)) return 'ar';
    if (/^(fa|per|prs)/i.test(ui)) return 'fa';
    if (IRAN_ZONES.test(String(zone || ''))) return 'fa';
    return 'en';
  }

  function browserZone() {
    try {
      return Intl.DateTimeFormat().resolvedOptions().timeZone || '';
    } catch (_) {
      return '';
    }
  }

  function resolveLang(pref) {
    if (pref === 'fa' || pref === 'en' || pref === 'ar') return pref;
    let ui = 'en';
    try {
      const api = globalThis.browser || globalThis.chrome;
      ui = (api && api.i18n && api.i18n.getUILanguage && api.i18n.getUILanguage()) ||
        (globalThis.navigator && navigator.language) || 'en';
    } catch (_) {
      ui = (globalThis.navigator && navigator.language) || 'en';
    }
    return langFromLocaleAndZone(ui, browserZone());
  }

  function t(key, lang) {
    const l = resolveLang(lang);
    const table = DICT[l] || DICT.en;
    if (table[key] != null) return table[key];
    if (DICT.fa[key] != null) return DICT.fa[key];
    return key;
  }

  function applyDom(root, lang) {
    const l = resolveLang(lang);
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      const val = t(el.getAttribute('data-i18n'), l);
      if (typeof val === 'string') el.textContent = val;
    });
    scope.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        const parts = pair.split(':');
        const attr = (parts[0] || '').trim();
        const key = (parts[1] || '').trim();
        if (!attr || !key) return;
        const val = t(key, l);
        if (typeof val === 'string') el.setAttribute(attr, val);
      });
    });
    const html = document.documentElement;
    if (html) {
      html.setAttribute('lang', l);
      html.setAttribute('dir', (l === 'fa' || l === 'ar') ? 'rtl' : 'ltr');
    }
    return l;
  }

  globalThis.HamsooI18n = {
    DICT: DICT,
    resolveLang: resolveLang,
    langFromLocaleAndZone: langFromLocaleAndZone,
    t: t,
    applyDom: applyDom
  };
